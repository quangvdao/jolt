fn route_fixture() -> Result<Vec<RouterShape>, BenchError> {
    synthetic_router_shapes()?
        .into_iter()
        .zip(REFERENCE_ROUTES)
        .zip([36_599, 14_464, 3_376, 20_804, 128])
        .map(|((shape, encoded), count)| {
            let mut deltas = Vec::with_capacity(count);
            for token in encoded.split_ascii_whitespace() {
                let (distance, value) = token.split_once(':').ok_or(BenchError::RouteFixture)?;
                let distance: usize = distance.parse().map_err(|_| BenchError::RouteFixture)?;
                let value: usize = value.parse().map_err(|_| BenchError::RouteFixture)?;
                if distance == 0 {
                    deltas.push(value);
                } else {
                    for _ in 0..value {
                        let at = deltas
                            .len()
                            .checked_sub(distance)
                            .ok_or(BenchError::RouteFixture)?;
                        let delta = *deltas.get(at).ok_or(BenchError::RouteFixture)?;
                        deltas.push(delta);
                    }
                }
            }
            if deltas.len() != count {
                return Err(BenchError::RouteFixture);
            }
            let mut packed = 0;
            let route = deltas
                .into_iter()
                .map(|delta| {
                    packed += delta;
                    RouteEntry {
                        output: packed >> 19,
                        source: (packed >> 9) & 1023,
                        selector: packed & 511,
                    }
                })
                .collect();
            let result = RouterShape::new(RouterShapeRequest {
                slots: shape.slots(),
                bank: shape.bank().to_vec(),
                factors: shape.factors().to_vec(),
                word_slots: shape.word_slots().to_vec(),
                log_outputs: shape.log_outputs(),
                route,
            })?;
            if result.route().len() != count {
                return Err(BenchError::RouteFixture);
            }
            Ok(result)
        })
        .collect()
}

// Fixture for the two row-weight views; item 1 owns memory::row_weights.
fn bytecode_address_weights(
    plan: &ScatterPlan<SyntheticTrace>,
    point: &[F128],
    weight: Weight,
) -> Result<Vec<F128>, RunnerError> {
    let split = point.len() / 2;
    let low = eq_table(&point[..split], None);
    let high = eq_table(&point[split..], None);
    plan.scatter(|cycle| {
        let index = match weight {
            Weight::Eq => cycle,
            Weight::Next if cycle == 0 => return F128::from_raw(0),
            Weight::Next => cycle - 1,
        };
        low[index & (low.len() - 1)] * high[index >> split]
    })
    .map_err(|error| RunnerError::Core {
        message: error.to_string(),
    })
}

impl Fixture {
    fn new(source: Arc<SyntheticTrace>) -> Result<Self, BenchError> {
        let entry = source.bytecode_index(0);
        let log_t = source.cycles().ilog2() as usize;
        let points: [Vec<F128>; 3] = std::array::from_fn(|member| {
            (0..log_t)
                .map(|i| F128::from_raw(0x987 + 53 * i as u128 + 0x1021 * member as u128))
                .collect()
        });
        let trace = Arc::new(ValidatedTrace::new(source)?);
        let plan = ScatterPlan::new(Arc::clone(&trace))?;
        let shapes = route_fixture()?;
        let layout = FoldLayout::new(&trace, &shapes, &vec![vec![]; shapes.len()])?;
        let folded = fold_pass(&trace, &shapes, &points[0], &plan, &layout, &[])?;
        let routed = routed_columns(&shapes, &folded.folds)?;
        let mut rng = ChaCha20Rng::seed_from_u64(0x8349);
        let matrix: Vec<_> = (0..routed.len()).map(|_| field(&mut rng)).collect();
        let inner_pairs = vec![
            (matrix.clone(), routed),
            (
                matrix.clone(),
                (0..matrix.len()).map(|_| field(&mut rng)).collect(),
            ),
            (
                matrix,
                (0..1 << shapes[0].log_outputs())
                    .map(|_| field(&mut rng))
                    .collect(),
            ),
        ];
        let mut weights: Vec<_> = points
            .iter()
            .map(|point| bytecode_address_weights(&plan, point, Weight::Eq))
            .collect::<Result<_, _>>()?;
        let mut next = bytecode_address_weights(&plan, &points[0], Weight::Next)?;
        next[entry] += F128::from_raw(1);
        weights.push(next);
        let bytecode_pairs = weights
            .into_iter()
            .map(|r| {
                let h = (0..r.len()).map(|_| field(&mut rng)).collect();
                (h, r)
            })
            .collect();
        Ok(Self {
            shapes,
            folds: folded.folds,
            plan,
            points,
            entry,
            inner: Input::new(inner_pairs),
            bytecode: Input::new(bytecode_pairs),
        })
    }
}
impl Input {
    fn new(pairs: Vec<(Vec<F128>, Vec<F128>)>) -> Self {
        let claim = pairs
            .iter()
            .flat_map(|(h, r)| h.iter().zip(r))
            .fold(F128::from_raw(0), |sum, (&h, &r)| sum + h * r);
        Self { pairs, claim }
    }
}
fn inner_threshold(log_t: usize, _threads: usize) -> f64 {
    79_000.0 / (1_usize << log_t) as f64
}
fn bytecode_threshold(log_t: usize, threads: usize) -> f64 {
    (if log_t == 22 { 15.0 } else { 37.0 }) / if threads == 12 { 9.6 } else { 1.0 }
}
#[expect(
    clippy::print_stdout,
    reason = "per-proof phase units are benchmark output"
)]
fn report(record: &Record, member: &Member) {
    if matches!(member, Member::Inner) {
        let scale = (1_usize << record.log_t) as f64 / 1_000.0;
        println!(
            "inner/routes/{}/{} total_min_us={:.6} total_median_us={:.6} threshold_us=79",
            record.log_t,
            record.threads,
            record.total.min * scale,
            record.total.median * scale
        );
        for (name, summary) in [
            "construct",
            "rounds",
            "finish",
            "extract",
            "views",
            "core_new",
        ]
        .into_iter()
        .zip(&record.phases)
        {
            println!(
                "inner_phase/routes/{}/{} phase={name} min_us={:.6} median_us={:.6}",
                record.log_t,
                record.threads,
                summary.min * scale,
                summary.median * scale
            );
        }
    }
}
fn main() -> Result<(), RunnerError> {
    let mut inner = Case::core("inner", Member::Inner, &["views", "core_new"]);
    inner.threshold = Some(inner_threshold);
    let mut bytecode = Case::core(
        "bytecode_address",
        Member::BytecodeAddress,
        &["views", "core_new"],
    );
    bytecode.threshold = Some(bytecode_threshold);
    let _ = run_prepared_cases(
        &[SynthProfile::AllRows],
        &[inner, bytecode],
        Fixture::new,
        |fixture, member| {
            let input = match member {
                Member::Inner => &fixture.inner,
                Member::BytecodeAddress => &fixture.bytecode,
            };
            Ok::<_, BenchError>(Input {
                pairs: input.pairs.clone(),
                claim: input.claim,
            })
        },
        |fixture, mut input, member, point, times| {
            let clock = Clock::start();
            match member {
                Member::Inner => {
                    input.pairs[0].1 = routed_columns(&fixture.shapes, &fixture.folds)?;
                }
                Member::BytecodeAddress => {
                    input.pairs[2].1 =
                        bytecode_address_weights(&fixture.plan, &fixture.points[2], Weight::Eq)?;
                    let mut next =
                        bytecode_address_weights(&fixture.plan, &fixture.points[0], Weight::Next)?;
                    next[fixture.entry] += F128::from_raw(1);
                    input.pairs[3].1 = next;
                }
            }
            let views = clock.elapsed();
            let clock = Clock::start();
            let mut core = PairSumCore::new(input.pairs)?;
            let construction = clock.elapsed();
            times.set(0, views + construction);
            times.set(4, views);
            times.set(5, construction);
            let run = core_rounds(&mut core, input.claim, point)?;
            times.set(1, run.rounds);
            times.set(2, run.finish);
            let clock = Clock::start();
            let _ = black_box(core.final_values());
            times.set(3, clock.elapsed());
            Ok::<_, BenchError>(core)
        },
        |_, _| {},
        |record, _, member| report(record, member),
    )?;
    Ok(())
}

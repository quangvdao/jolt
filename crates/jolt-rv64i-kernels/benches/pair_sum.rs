struct Input {
    pairs: Vec<(Vec<F128>, Vec<F128>)>,
    claim: F128,
}
impl PreparedInput for Input {
    fn input_bytes(&self) -> usize {
        self.pairs
            .iter()
            .map(|(h, r)| (h.capacity() + r.capacity()) * size_of::<F128>())
            .sum()
    }
}
